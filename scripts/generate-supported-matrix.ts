/**
 * Generates docs/SUPPORTED_MATRIX.md from formats.ts and converter capability sets.
 * Run: npx tsx scripts/generate-supported-matrix.ts
 */
import { writeFileSync } from "fs";
import { join } from "path";
import { formats, isConversionPairListed, type FormatCategory } from "../src/lib/formats";
import {
  imageInputFormats,
  imageOutputFormats,
  dataOutputFormats,
  docOutputFormats,
  subtitleOutputFormats,
  archiveOutputFormats,
  ebookOutputFormats,
  presentationOutputFormats,
  fontOutputFormats,
} from "../src/lib/converter";

const CATEGORY_OUTPUT: Partial<Record<FormatCategory, Set<string>>> = {
  image: imageOutputFormats,
  data: dataOutputFormats,
  document: docOutputFormats,
  subtitle: subtitleOutputFormats,
  archive: archiveOutputFormats,
  ebook: ebookOutputFormats,
  presentation: presentationOutputFormats,
  font: fontOutputFormats,
};

function statusForPair(src: string, dst: string, category: FormatCategory): string {
  if (src === dst) return "—";
  const listed = isConversionPairListed(src, dst);
  if (!listed) return "—";

  if (category === "image") {
    if (!imageInputFormats.has(src)) return "—";
    if (!imageOutputFormats.has(dst)) return "—";
    return "✓";
  }

  const outs = CATEGORY_OUTPUT[category];
  if (outs && !outs.has(dst)) return "—";
  return "✓";
}

function main() {
  const lines: string[] = [
    "# Supported conversion matrix",
    "",
    "Auto-generated by `npx tsx scripts/generate-supported-matrix.ts`.",
    "✓ = listed in UI and routed by the converter for that category.",
    "— = not offered or not supported.",
    "",
    `Generated: ${new Date().toISOString()}`,
    "",
  ];

  const categories = [
    "image",
    "audio",
    "document",
    "data",
    "archive",
    "ebook",
    "presentation",
    "subtitle",
    "font",
    "other",
  ] as FormatCategory[];

  for (const cat of categories) {
    const fmts = formats.filter((f) => f.category === cat);
    if (!fmts.length) continue;

    lines.push(`## ${cat.charAt(0).toUpperCase() + cat.slice(1)} (${fmts.length} formats)`);
    lines.push("");

    if (cat === "image") {
      lines.push(
        `**Inputs:** ${fmts.length} formats · **Outputs:** ${[...imageOutputFormats].sort().join(", ")}`,
      );
      lines.push("");
    }

    const allTargets = new Set<string>();
    for (const f of fmts) {
      for (const t of f.targetFormats) allTargets.add(t);
    }
    const targets = [...allTargets].sort();

    lines.push("| Source | " + targets.map((t) => t.toUpperCase()).join(" | ") + " |");
    lines.push("|--------|" + targets.map(() => "---").join("|") + "|");

    for (const f of fmts) {
      const row = [f.ext.toUpperCase()];
      for (const t of targets) {
        row.push(statusForPair(f.ext, t, cat));
      }
      lines.push("| " + row.join(" | ") + " |");
    }
    lines.push("");
  }

  lines.push("## Notes");
  lines.push("");
  lines.push("- **Image:** exotic inputs (PSD, DDS, QOI, PCX, …) are decoded via `image-decode.ts` then converted with sharp. TGS is not offered (needs Lottie).");
  lines.push("- **Data:** ORC, XPT, and Toon are not listed in the UI (unsupported readers).");
  lines.push("- **Ebook:** Kindle/legacy inputs (MOBI, AZW3, LRF, PDB, SNB) are not listed; EPUB/FB2/comics remain.");
  lines.push("- **Font:** Only OTF/TTF/WOFF → WOFF2 and WOFF2 → TTF (no passthrough pairs).");
  lines.push("- **Presentation:** Text extract + rewrap; not full slide fidelity.");
  lines.push("- **Audio / Archive:** May require ffmpeg, RAR CLI, LibreOffice, or Node zstd depending on host.");
  lines.push("");

  const outPath = join(process.cwd(), "docs", "SUPPORTED_MATRIX.md");
  writeFileSync(outPath, lines.join("\n"), "utf-8");
  console.log(`Wrote ${outPath}`);
}

main();
